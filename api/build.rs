use core::error::Error;
use core::fmt::{self, Write as _};
use std::collections::BTreeSet;
use std::fs;
use std::path::PathBuf;

use heck::{ToSnakeCase as _, ToUpperCamelCase as _};
use prost_reflect::{DescriptorPool, FieldDescriptor, Kind, MessageDescriptor};

fn main() -> Result<(), Box<dyn Error>> {
    println!("cargo::rerun-if-env-changed=DEP_VALVEPROTOS_DESCRIPTORS");

    let Ok(descriptors_path) = std::env::var("DEP_VALVEPROTOS_DESCRIPTORS") else {
        println!("cargo::warning=DEP_VALVEPROTOS_DESCRIPTORS not set, skipping event codegen");
        return Ok(());
    };

    println!("cargo::rerun-if-changed={descriptors_path}");

    let descriptors = fs::read(&descriptors_path)
        .map_err(|e| format!("failed to read {descriptors_path}: {e}"))?;
    let pool = DescriptorPool::decode(&*descriptors)
        .map_err(|e| format!("failed to decode descriptors: {e}"))?;

    let generated = generate_events_code(&pool)?;

    let out_dir = PathBuf::from(std::env::var("OUT_DIR")?);
    let out_path = out_dir.join("events_generated.rs");
    fs::write(&out_path, &generated)
        .map_err(|e| format!("failed to write {}: {e}", out_path.display()))?;
    Ok(())
}

fn generate_events_code(pool: &DescriptorPool) -> Result<String, Box<dyn Error>> {
    let event_mappings = extract_event_mappings(pool)?;

    let mut body = Body::default();
    generate_event_type_enum(&mut body.code, &event_mappings)?;
    generate_decoded_event_enum(&mut body.code, &event_mappings)?;
    generate_decode_function(&mut body.code, &event_mappings)?;
    generate_event_schema(&mut body.code, &event_mappings)?;
    generate_append_impl(&mut body, &event_mappings)?;
    generate_column_helpers(&mut body.code);

    let mut code = String::new();
    code.push_str("// Auto-generated by build.rs - DO NOT EDIT\n\n");
    code.push_str("use std::sync::Arc;\n\n");
    let builders = body
        .builder_types
        .into_iter()
        .collect::<Vec<_>>()
        .join(", ");
    writeln!(
        code,
        "use datafusion::arrow::array::{{ArrayBuilder, {builders}}};"
    )?;
    code.push_str("use datafusion::arrow::datatypes::{DataType, Field, Fields, Schema};\n");
    code.push_str("use datafusion::arrow::error::ArrowError;\n\n");
    code.push_str(&body.code);
    Ok(code)
}

/// Generated items plus the arrow builder types they use, which become the `use` list.
#[derive(Default)]
struct Body {
    code: String,
    builder_types: BTreeSet<&'static str>,
}

#[derive(Debug, Clone)]
struct EventMapping {
    message_id: i32,
    enum_variant_name: String,
    message: MessageDescriptor,
    rust_type_path: String,
    table_name: String,
}

impl EventMapping {
    fn fn_suffix(&self) -> String {
        self.enum_variant_name.to_snake_case()
    }
}

#[expect(
    clippy::print_stderr,
    reason = "build script diagnostics go to the build's stderr log"
)]
fn extract_event_mappings(pool: &DescriptorPool) -> Result<Vec<EventMapping>, Box<dyn Error>> {
    let enum_desc = pool
        .get_enum_by_name("CitadelUserMessageIds")
        .ok_or("CitadelUserMessageIds enum not found")?;

    let mut mappings = Vec::new();

    for value in enum_desc.values() {
        let enum_name = value.name();
        let message_id = value.number();

        let Some(short_name) = enum_name.strip_prefix("k_EUserMsg_") else {
            continue;
        };

        let Some(message) = find_message_for_event(pool, short_name) else {
            eprintln!("Warning: No message found for {enum_name} (id={message_id})");
            continue;
        };

        let rust_type_path = format!(
            "valveprotos::deadlock::{}",
            proto_message_name_to_rust_type(message.name())
        );

        mappings.push(EventMapping {
            message_id,
            enum_variant_name: short_name.to_owned(),
            message,
            rust_type_path,
            table_name: format!("{short_name}Event"),
        });
    }

    mappings.sort_by_key(|m| m.message_id);
    Ok(mappings)
}

fn find_message_for_event(pool: &DescriptorPool, short_name: &str) -> Option<MessageDescriptor> {
    [
        format!("CCitadelUserMsg_{short_name}"),
        format!("CCitadelUserMessage_{short_name}"),
        format!("CCitadelUserMsg{short_name}"),
    ]
    .iter()
    .find_map(|candidate| pool.get_message_by_name(candidate))
}

fn generate_event_type_enum(code: &mut String, mappings: &[EventMapping]) -> fmt::Result {
    code.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\n");
    code.push_str("pub(super) enum EventType {\n");
    for mapping in mappings {
        writeln!(
            code,
            "    {} = {},",
            mapping.enum_variant_name, mapping.message_id
        )?;
    }
    code.push_str("}\n\n");

    code.push_str("impl EventType {\n");
    code.push_str("    pub(super) const fn table_name(self) -> &'static str {\n");
    code.push_str("        match self {\n");
    for mapping in mappings {
        writeln!(
            code,
            "            Self::{} => \"{}\",",
            mapping.enum_variant_name, mapping.table_name
        )?;
    }
    code.push_str("        }\n");
    code.push_str("    }\n\n");

    code.push_str("    pub(super) const fn message_id(self) -> u32 {\n");
    code.push_str("        match self {\n");
    for mapping in mappings {
        writeln!(
            code,
            "            Self::{} => {},",
            mapping.enum_variant_name, mapping.message_id
        )?;
    }
    code.push_str("        }\n");
    code.push_str("    }\n\n");

    code.push_str("    pub(super) const fn all() -> &'static [Self] {\n");
    code.push_str("        &[\n");
    for mapping in mappings {
        writeln!(code, "            Self::{},", mapping.enum_variant_name)?;
    }
    code.push_str("        ]\n");
    code.push_str("    }\n");

    code.push_str("}\n\n");
    Ok(())
}

fn generate_decoded_event_enum(code: &mut String, mappings: &[EventMapping]) -> fmt::Result {
    code.push_str("#[derive(Debug, Clone)]\n");
    code.push_str("pub(super) enum DecodedEvent {\n");
    for mapping in mappings {
        writeln!(
            code,
            "    {}({}),",
            mapping.enum_variant_name, mapping.rust_type_path
        )?;
    }
    code.push_str("}\n\n");
    Ok(())
}

fn generate_decode_function(code: &mut String, mappings: &[EventMapping]) -> fmt::Result {
    code.push_str(
        "pub(super) fn decode_event(message_id: u32, data: &[u8]) -> Option<DecodedEvent> {\n",
    );
    code.push_str("    use prost::Message as _;\n");
    code.push_str("    match message_id {\n");
    for mapping in mappings {
        writeln!(
            code,
            "        {} => {}::decode(data).ok().map(DecodedEvent::{}),",
            mapping.message_id, mapping.rust_type_path, mapping.enum_variant_name
        )?;
    }
    code.push_str("        _ => None,\n");
    code.push_str("    }\n");
    code.push_str("}\n\n");
    Ok(())
}

/// `event_schema` dispatches to one schema fn per event, so no fn grows with the event count
/// and events with identical columns don't produce identical match arms.
fn generate_event_schema(code: &mut String, mappings: &[EventMapping]) -> fmt::Result {
    code.push_str("pub(super) fn event_schema(table_name: &str) -> Option<Arc<Schema>> {\n");
    code.push_str("    match table_name {\n");
    for mapping in mappings {
        writeln!(
            code,
            "        \"{}\" => Some({}_schema()),",
            mapping.table_name,
            mapping.fn_suffix()
        )?;
    }
    code.push_str("        _ => None,\n");
    code.push_str("    }\n");
    code.push_str("}\n\n");

    for mapping in mappings {
        writeln!(
            code,
            "fn {}_schema() -> Arc<Schema> {{",
            mapping.fn_suffix()
        )?;
        code.push_str("    Arc::new(Schema::new(vec![\n");
        code.push_str("        Field::new(\"tick\", DataType::Int32, false),\n");
        for field in mapping.message.fields() {
            writeln!(
                code,
                "        Field::new(\"{}\", {}, true),",
                field.name(),
                field_to_arrow_type(&field)
            )?;
        }
        code.push_str("    ]))\n");
        code.push_str("}\n\n");
    }
    Ok(())
}

fn field_to_arrow_type(field: &FieldDescriptor) -> String {
    let kind = field.kind();

    if field.is_list() {
        let inner_type = scalar_or_message_arrow_type(&kind);
        return format!("DataType::List(Arc::new(Field::new(\"item\", {inner_type}, true)))");
    }

    scalar_or_message_arrow_type(&kind)
}

fn scalar_or_message_arrow_type(kind: &Kind) -> String {
    match kind {
        Kind::Int32 | Kind::Sint32 | Kind::Sfixed32 | Kind::Enum(_) => "DataType::Int32".to_owned(),
        Kind::Int64 | Kind::Sint64 | Kind::Sfixed64 => "DataType::Int64".to_owned(),
        Kind::Uint32 | Kind::Fixed32 => "DataType::UInt32".to_owned(),
        Kind::Uint64 | Kind::Fixed64 => "DataType::UInt64".to_owned(),
        Kind::Float => "DataType::Float32".to_owned(),
        Kind::Double => "DataType::Float64".to_owned(),
        Kind::Bool => "DataType::Boolean".to_owned(),
        Kind::String => "DataType::Utf8".to_owned(),
        Kind::Bytes => "DataType::Binary".to_owned(),
        Kind::Message(nested_desc) => {
            let fields = nested_desc
                .fields()
                .map(|nested_field| {
                    format!(
                        "Field::new(\"{}\", {}, true)",
                        nested_field.name(),
                        field_to_arrow_type(&nested_field)
                    )
                })
                .collect::<Vec<_>>();
            format!(
                "DataType::Struct(Fields::from(vec![{}]))",
                fields.join(", ")
            )
        }
    }
}

/// `append_event_to_builders` dispatches to one `AppendColumns` impl per event with columns;
/// events without columns share a single no-op arm. A trait impl (rather than a free fn per
/// event) takes `&self` without tripping `trivially_copy_pass_by_ref` on `Copy` messages.
fn generate_append_impl(body: &mut Body, mappings: &[EventMapping]) -> fmt::Result {
    let (with_fields, without_fields): (Vec<_>, Vec<_>) = mappings
        .iter()
        .partition(|mapping| mapping.message.fields().len() > 0);

    body.code.push_str(
        "pub(super) fn append_event_to_builders(
    event: &DecodedEvent,
    builders: &mut [Box<dyn ArrayBuilder>],
) -> Result<(), ArrowError> {
    match event {
",
    );
    for mapping in &with_fields {
        writeln!(
            body.code,
            "        DecodedEvent::{}(msg) => msg.append_columns(builders),",
            mapping.enum_variant_name,
        )?;
    }
    if !without_fields.is_empty() {
        let patterns = without_fields
            .iter()
            .map(|mapping| format!("DecodedEvent::{}(_)", mapping.enum_variant_name))
            .collect::<Vec<_>>();
        writeln!(body.code, "        {} => Ok(()),", patterns.join(" | "))?;
    }
    body.code.push_str("    }\n}\n\n");

    body.code.push_str(
        "trait AppendColumns {
    fn append_columns(&self, builders: &mut [Box<dyn ArrayBuilder>]) -> Result<(), ArrowError>;
}

",
    );
    for mapping in &with_fields {
        writeln!(
            body.code,
            "impl AppendColumns for {} {{",
            mapping.rust_type_path
        )?;
        body.code.push_str(
            "    fn append_columns(&self, builders: &mut [Box<dyn ArrayBuilder>]) -> Result<(), ArrowError> {\n",
        );
        generate_field_appends(body, &mapping.message)?;
        body.code.push_str("        Ok(())\n    }\n}\n\n");
    }
    Ok(())
}

/// Emits `column`, the checked lookup every generated append goes through: a column whose
/// builder is missing or of another type fails the append instead of panicking.
fn generate_column_helpers(code: &mut String) {
    code.push_str(
        "fn column<T: ArrayBuilder>(builders: &mut [Box<dyn ArrayBuilder>], idx: usize) -> Result<&mut T, ArrowError> {
    builders
        .get_mut(idx)
        .and_then(|builder| builder.as_any_mut().downcast_mut::<T>())
        .ok_or_else(|| {
            ArrowError::SchemaError(format!(
                \"event column {idx} is not a {}\",
                core::any::type_name::<T>()
            ))
        })
}
",
    );
}

fn generate_field_appends(body: &mut Body, msg_desc: &MessageDescriptor) -> fmt::Result {
    for (i, field) in msg_desc.fields().enumerate() {
        let rust_field_name = proto_field_to_rust_name(field.name());

        let ctx = GenContext {
            parent: "builders".to_owned(),
            index: i,
            source_expr: "self".to_owned(),
            depth: 0,
        };

        let append_code = generate_field_append(body, &field, &rust_field_name, &ctx)?;
        writeln!(body.code, "        {append_code}")?;
    }
    Ok(())
}

fn proto_field_to_rust_name(proto_name: &str) -> String {
    const RUST_KEYWORDS: &[&str] = &[
        "as", "async", "await", "break", "const", "continue", "crate", "dyn", "else", "enum",
        "extern", "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move",
        "mut", "override", "pub", "ref", "return", "self", "Self", "static", "struct", "super",
        "trait", "true", "type", "unsafe", "use", "where", "while", "abstract", "become", "box",
        "do", "final", "macro", "offsetof", "priv", "proc", "pure", "sizeof", "typeof", "unsized",
        "virtual", "yield", "try",
    ];

    if RUST_KEYWORDS.contains(&proto_name) {
        format!("r#{proto_name}")
    } else {
        proto_name.to_owned()
    }
}

fn proto_message_name_to_rust_type(proto_name: &str) -> String {
    proto_name.to_upper_camel_case()
}

/// Where a field's builder lives: column `index` of the top-level `builders` slice
/// (depth 0) or child `index` of the struct builder expression `parent`.
struct GenContext {
    parent: String,
    index: usize,
    source_expr: String,
    depth: usize,
}

impl GenContext {
    fn var_name(&self, base: &str) -> String {
        if self.depth == 0 {
            base.to_owned()
        } else {
            format!("{}_{}", base, self.depth)
        }
    }

    /// Expression yielding `&mut builder_type` for this field, propagating a lookup error.
    fn builder(&self, builder_type: &str) -> String {
        if self.depth == 0 {
            format!("column::<{builder_type}>({}, {})?", self.parent, self.index)
        } else {
            format!(
                "column::<{builder_type}>({}.field_builders_mut(), {})?",
                self.parent, self.index
            )
        }
    }
}

const fn scalar_builder_type(kind: &Kind) -> &'static str {
    match kind {
        Kind::Int32 | Kind::Sint32 | Kind::Sfixed32 | Kind::Enum(_) => "Int32Builder",
        Kind::Int64 | Kind::Sint64 | Kind::Sfixed64 => "Int64Builder",
        Kind::Uint32 | Kind::Fixed32 => "UInt32Builder",
        Kind::Uint64 | Kind::Fixed64 => "UInt64Builder",
        Kind::Float => "Float32Builder",
        Kind::Double => "Float64Builder",
        Kind::Bool => "BooleanBuilder",
        Kind::String => "StringBuilder",
        Kind::Bytes => "BinaryBuilder",
        Kind::Message(_) => "StructBuilder",
    }
}

fn scalar_builder(body: &mut Body, kind: &Kind) -> &'static str {
    let builder_type = scalar_builder_type(kind);
    body.builder_types.insert(builder_type);
    builder_type
}

fn list_builder(body: &mut Body, kind: &Kind) -> String {
    body.builder_types.insert("ListBuilder");
    format!("ListBuilder<{}>", scalar_builder(body, kind))
}

fn generate_field_append(
    body: &mut Body,
    field: &FieldDescriptor,
    rust_field_name: &str,
    ctx: &GenContext,
) -> Result<String, fmt::Error> {
    let kind = field.kind();

    if field.is_list() {
        return generate_list_append(body, field, rust_field_name, ctx);
    }

    if let Kind::Message(nested_desc) = &kind {
        return generate_message_append(body, nested_desc, rust_field_name, ctx);
    }

    let builder_type = scalar_builder(body, &kind);
    Ok(format!(
        "{}.append_option({});",
        ctx.builder(builder_type),
        generate_value_expr(&kind, &ctx.source_expr, rust_field_name)
    ))
}

// Null entry for child `child_idx` of the struct builder expression `parent` (`sb`, or
// `lb.values()` for list items). A null nested message still appends a null to each of its
// children: a `StructBuilder` whose children lag behind its own length panics on `finish`.
fn child_field_null(
    body: &mut Body,
    parent: &str,
    depth: usize,
    child_idx: usize,
    child_field: &FieldDescriptor,
) -> String {
    let child_kind = child_field.kind();
    if child_field.is_list() {
        let builder_type = list_builder(body, &child_kind);
        return format!(
            "column::<{builder_type}>({parent}.field_builders_mut(), {child_idx})?.append(false);"
        );
    }
    let builder_type = scalar_builder(body, &child_kind);
    let Kind::Message(nested_desc) = &child_kind else {
        return format!(
            "column::<{builder_type}>({parent}.field_builders_mut(), {child_idx})?.append_null();"
        );
    };
    let sb_var = format!("sb_{depth}");
    let mut code = format!(
        "{{ let {sb_var} = column::<{builder_type}>({parent}.field_builders_mut(), {child_idx})?; "
    );
    for (idx, field) in nested_desc.fields().enumerate() {
        code.push_str(&child_field_null(
            body,
            &sb_var,
            depth.saturating_add(1),
            idx,
            &field,
        ));
        code.push(' ');
    }
    code.push_str(&sb_var);
    code.push_str(".append(false); }");
    code
}

fn generate_list_append(
    body: &mut Body,
    field: &FieldDescriptor,
    rust_field_name: &str,
    ctx: &GenContext,
) -> Result<String, fmt::Error> {
    let kind = field.kind();
    let lb_var = ctx.var_name("lb");
    let item_var = ctx.var_name("item");

    let builder_type = list_builder(body, &kind);
    let mut code = format!("{{ let {lb_var} = {}; ", ctx.builder(&builder_type));

    write!(
        code,
        "for {} in &{}.{} {{ ",
        item_var, ctx.source_expr, rust_field_name
    )?;

    if let Kind::Message(nested_desc) = &kind {
        let values = format!("{lb_var}.values()");
        for (child_idx, child_field) in nested_desc.fields().enumerate() {
            let child_ctx = GenContext {
                parent: values.clone(),
                index: child_idx,
                source_expr: item_var.clone(),
                depth: ctx.depth.saturating_add(1),
            };
            let child_rust_name = proto_field_to_rust_name(child_field.name());
            code.push_str(&generate_field_append(
                body,
                &child_field,
                &child_rust_name,
                &child_ctx,
            )?);
            code.push(' ');
        }
        write!(code, "{values}.append(true); ")?;
    } else {
        let value_expr = match &kind {
            Kind::String | Kind::Bytes => item_var.clone(),
            _ => format!("*{item_var}"),
        };
        write!(code, "{lb_var}.values().append_value({value_expr}); ")?;
    }

    code.push_str("} ");
    write!(code, "{lb_var}.append(true); }}")?;

    Ok(code)
}

// prost stores enum fields as `i32`, so they need no conversion.
fn generate_value_expr(kind: &Kind, source: &str, field_name: &str) -> String {
    match kind {
        Kind::String | Kind::Bytes => format!("{source}.{field_name}.as_deref()"),
        _ => format!("{source}.{field_name}"),
    }
}

fn generate_message_append(
    body: &mut Body,
    nested_desc: &MessageDescriptor,
    rust_field_name: &str,
    ctx: &GenContext,
) -> Result<String, fmt::Error> {
    let sb_var = ctx.var_name("sb");
    let nested_var = ctx.var_name("nested");

    let builder_type = scalar_builder(body, &Kind::Message(nested_desc.clone()));
    let mut code = format!("{{ let {sb_var} = {}; ", ctx.builder(builder_type));

    write!(
        code,
        "if let Some({}) = &{}.{} {{ ",
        nested_var, ctx.source_expr, rust_field_name
    )?;

    for (child_idx, child_field) in nested_desc.fields().enumerate() {
        let child_ctx = GenContext {
            parent: sb_var.clone(),
            index: child_idx,
            source_expr: nested_var.clone(),
            depth: ctx.depth.saturating_add(1),
        };
        let child_rust_name = proto_field_to_rust_name(child_field.name());
        code.push_str(&generate_field_append(
            body,
            &child_field,
            &child_rust_name,
            &child_ctx,
        )?);
        code.push(' ');
    }

    write!(code, "{sb_var}.append(true); ")?;
    code.push_str("} else { ");

    for (child_idx, child_field) in nested_desc.fields().enumerate() {
        code.push_str(&child_field_null(
            body,
            &sb_var,
            ctx.depth.saturating_add(1),
            child_idx,
            &child_field,
        ));
        code.push(' ');
    }

    write!(code, "{sb_var}.append(false); ")?;
    code.push_str("} }");

    Ok(code)
}
