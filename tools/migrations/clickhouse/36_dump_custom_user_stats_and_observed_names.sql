-- Public data-lake export layer, follow-up to 35_public_dump.sql.
--
-- 1. stats.custom_user_stats joins the match_player view. The dump service treats the new
--    column as an additive schema change: the generation is kept, hourly deltas carry it from
--    the next tick on, and every existing per-partition base file is rebuilt (a bounded number
--    per tick, see data_dump::compaction) until all past partitions carry it.
-- 2. steam_profile_observed_names is published as an hourly snapshot. observed_at is the
--    start time of the match the name was seen in, not the insert time, so it cannot serve as
--    an incremental watermark; the table is small enough for a full export every tick.

