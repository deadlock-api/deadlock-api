CREATE TABLE default.player_match_recap
(
    `account_id` UInt32,
    `match_id` UInt64 CODEC(Delta(8), ZSTD(1)),
    `start_time` DateTime CODEC(Delta(4), ZSTD(1)),
    `game_mode` Enum8('Invalid' = 0, 'Normal' = 1, 'OneVsOneTest' = 2, 'Sandbox' = 3, 'StreetBrawl' = 4, 'ExploreNYC' = 5, 'Internal' = 6, 'Internal02' = 7),
    `match_mode` Enum8('Invalid' = 0, 'Unranked' = 1, 'PrivateLobby' = 2, 'CoopBot' = 3, 'Ranked' = 4, 'ServerTest' = 5, 'Tutorial' = 6, 'HeroLabs' = 7, 'NewPlayerPlacement' = 8),
    `team` Enum8('Team0' = 0, 'Team1' = 1, 'Spectator' = 16),
    `player_slot` UInt8,
    `assigned_lane` UInt8 COMMENT 'Lane the player was assigned: 1, 4 or 6 (rarely 0)',
    `party` UInt32 COMMENT 'Party id, 0 = solo',
    `abandon_match_time_s` UInt32 CODEC(T64, ZSTD(1)),
    `player_healing` UInt32 CODEC(T64, ZSTD(1)),
    `teammate_healing` UInt32 CODEC(T64, ZSTD(1)),
    `teammate_barriering` UInt32 CODEC(T64, ZSTD(1)),
    `self_healing` UInt32 CODEC(T64, ZSTD(1)),
    `headshot_kills` UInt32 CODEC(T64, ZSTD(1)),
    `bullet_kills` UInt32 CODEC(T64, ZSTD(1)),
    `melee_kills` UInt32 CODEC(T64, ZSTD(1)),
    `ability_kills` UInt32 CODEC(T64, ZSTD(1)),
    `time_dead_s` UInt32 COMMENT 'Sum of death_details.death_duration_s' CODEC(T64, ZSTD(1)),
    `killer_hero_ids` Array(UInt8) COMMENT 'Hero of the killer of each death, in death order; 0 = no hero (trooper, guardian, ...) or unknown slot_hero_ids',
    `upgrade_ids` Array(UInt32) COMMENT 'upgrades.item_id: shop items bought, in buy order',
    `accolade_ids` Array(UInt16),
    `enemy_hero_ids` Array(UInt8),
    `parries` UInt32 COMMENT 'Custom stat Parry Success' CODEC(T64, ZSTD(1)),
    `parry_misses` UInt32 COMMENT 'Custom stat Parry Miss' CODEC(T64, ZSTD(1)),
    `unspent_gold_minutes` UInt32 COMMENT 'Custom stat Unspent Gold Minutes: souls held unspent summed over match minutes' CODEC(T64, ZSTD(1)),
    `breakables_broken` UInt32 COMMENT 'Custom stat PowerUp Gold (a count of breakables)' CODEC(T64, ZSTD(1)),
    `comeback_gold` UInt32 CODEC(T64, ZSTD(1)),
    `gold_players` UInt32 CODEC(T64, ZSTD(1)),
    `gold_lane_creeps` UInt32 CODEC(T64, ZSTD(1)),
    `gold_neutrals` UInt32 CODEC(T64, ZSTD(1)),
    `gold_bosses` UInt32 CODEC(T64, ZSTD(1)),
    `gold_treasure` UInt32 CODEC(T64, ZSTD(1)),
    `gold_breakables` UInt32 CODEC(T64, ZSTD(1)),
    `gold_death_loss` UInt32 CODEC(T64, ZSTD(1)),
    `dm_sources` Array(LowCardinality(String)) COMMENT 'Ability, item and weapon sources (damage_matrix.source without the Bullet/Ability/Melee/Misc/UnknownAbility/ability_unknown categories) of the player\'s damage to enemy heroes',
    `dm_source_damage` Array(UInt32) COMMENT 'Damage to enemy heroes per dm_sources entry' CODEC(T64, ZSTD(1)),
    `dm_bullet` UInt32 COMMENT 'damage_matrix category Bullet: weapon-type damage to enemy heroes' CODEC(T64, ZSTD(1)),
    `dm_ability` UInt32 COMMENT 'damage_matrix category Ability: spirit-type damage to enemy heroes' CODEC(T64, ZSTD(1)),
    `dm_melee` UInt32 COMMENT 'damage_matrix category Melee: melee damage to enemy heroes' CODEC(T64, ZSTD(1)),
    `dm_target_hero_ids` Array(UInt8) COMMENT 'Enemy heroes the player damaged (slot_hero_ids of the damaged slots); a hero can repeat in Street Brawl',
    `dm_target_damage` Array(UInt32) COMMENT 'Damage per dm_target_hero_ids entry, summed over the specific sources' CODEC(T64, ZSTD(1)),
    `cc_ms` UInt32 COMMENT 'Crowd control the player applied to enemy heroes, in milliseconds' CODEC(T64, ZSTD(1)),
    `cc_stun_ms` UInt32 COMMENT 'Stun part of cc_ms' CODEC(T64, ZSTD(1)),
    `heal_prevented` UInt32 COMMENT 'Enemy healing the player prevented' CODEC(T64, ZSTD(1)),
    `damage_mitigated_dm` UInt32 COMMENT 'damage_matrix mitigated_by_source total: damage the player\'s resistances, barriers and abilities prevented' CODEC(T64, ZSTD(1))
)
ENGINE = ReplacingMergeTree
PARTITION BY toYear(start_time)
ORDER BY (account_id, match_id)
SETTINGS index_granularity = 1024, default_compression_codec = 'ZSTD(1)'
COMMENT 'One row per (account, Ranked/Unranked Normal or Street Brawl match) with the per-match extras of the yearly recap (/v1/players/{account_id}/year-recap) that player_match_stats lacks: team, lane, healing, kill types, deaths by killer hero, items, accolades, custom stats, soul sources and per-source/per-target damage matrix sums. Fed by player_match_recap_mv; 2026 backfilled from match_player after the damage matrix backfill';
