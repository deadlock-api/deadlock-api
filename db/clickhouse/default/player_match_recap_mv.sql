CREATE MATERIALIZED VIEW default.player_match_recap_mv TO default.player_match_recap
(
    `account_id` UInt32,
    `match_id` UInt64,
    `start_time` DateTime,
    `game_mode` Enum8('Invalid' = 0, 'Normal' = 1, 'OneVsOneTest' = 2, 'Sandbox' = 3, 'StreetBrawl' = 4, 'ExploreNYC' = 5, 'Internal' = 6, 'Internal02' = 7),
    `match_mode` Enum8('Invalid' = 0, 'Unranked' = 1, 'PrivateLobby' = 2, 'CoopBot' = 3, 'Ranked' = 4, 'ServerTest' = 5, 'Tutorial' = 6, 'HeroLabs' = 7, 'NewPlayerPlacement' = 8),
    `team` Enum8('Team0' = 0, 'Team1' = 1, 'Spectator' = 16),
    `player_slot` UInt8,
    `assigned_lane` UInt8,
    `party` UInt32,
    `abandon_match_time_s` UInt32,
    `player_healing` UInt32,
    `teammate_healing` UInt32,
    `teammate_barriering` UInt32,
    `self_healing` UInt32,
    `headshot_kills` UInt32,
    `bullet_kills` UInt32,
    `melee_kills` UInt32,
    `ability_kills` UInt32,
    `time_dead_s` UInt32,
    `killer_hero_ids` Array(UInt8),
    `upgrade_ids` Array(UInt32),
    `accolade_ids` Array(UInt16),
    `enemy_hero_ids` Array(UInt8),
    `parries` UInt32,
    `parry_misses` UInt32,
    `unspent_gold_minutes` UInt32,
    `breakables_broken` UInt32,
    `comeback_gold` UInt32,
    `gold_players` UInt32,
    `gold_lane_creeps` UInt32,
    `gold_neutrals` UInt32,
    `gold_bosses` UInt32,
    `gold_treasure` UInt32,
    `gold_breakables` UInt32,
    `gold_death_loss` UInt32,
    `dm_sources` Array(String),
    `dm_source_damage` Array(UInt32),
    `dm_bullet` UInt32,
    `dm_ability` UInt32,
    `dm_melee` UInt32,
    `dm_target_hero_ids` Array(UInt8),
    `dm_target_damage` Array(UInt32),
    `cc_ms` UInt32,
    `cc_stun_ms` UInt32,
    `heal_prevented` UInt32,
    `damage_mitigated_dm` UInt32
)
AS SELECT
    account_id,
    match_id,
    start_time,
    game_mode,
    match_mode,
    team,
    player_slot,
    assigned_lane,
    party,
    abandon_match_time_s,
    player_healing,
    teammate_healing,
    teammate_barriering,
    self_healing,
    headshot_kills,
    bullet_kills,
    melee_kills,
    ability_kills,
    time_dead_s,
    killer_hero_ids,
    upgrade_ids,
    accolade_ids,
    enemy_hero_ids,
    parries,
    parry_misses,
    unspent_gold_minutes,
    breakables_broken,
    comeback_gold,
    gold_players,
    gold_lane_creeps,
    gold_neutrals,
    gold_bosses,
    gold_treasure,
    gold_breakables,
    gold_death_loss,
    dm_sources,
    dm_source_damage,
    dm_bullet,
    dm_ability,
    dm_melee,
    dm_target_hero_ids,
    dm_target_damage,
    cc_ms,
    cc_stun_ms,
    heal_prevented,
    damage_mitigated_dm
FROM
(
    SELECT
        account_id,
        match_id,
        start_time,
        game_mode,
        match_mode,
        team,
        toUInt8(player_slot) AS player_slot,
        toUInt8(assigned_lane) AS assigned_lane,
        ifNull(party, 0) AS party,
        abandon_match_time_s,
        max_player_healing AS player_healing,
        max_teammate_healing AS teammate_healing,
        max_teammate_barriering AS teammate_barriering,
        max_self_healing AS self_healing,
        final_stats.headshot_kills AS headshot_kills,
        final_stats.bullet_kills AS bullet_kills,
        final_stats.melee_kills AS melee_kills,
        final_stats.ability_kills AS ability_kills,
        toUInt32(arraySum(death_details.death_duration_s)) AS time_dead_s,
        arrayMap(s -> (slot_hero_ids[s + 1]), death_details.killer_player_slot) AS killer_hero_ids,
        arrayMap(x -> toUInt32(x), upgrades.item_id) AS upgrade_ids,
        arrayMap(x -> toUInt16(x), accolades.accolade_id) AS accolade_ids,
        enemy_hero_ids,
        final_stats.custom_user_stats['Parry Success'] AS parries,
        final_stats.custom_user_stats['Parry Miss'] AS parry_misses,
        final_stats.custom_user_stats['Unspent Gold Minutes'] AS unspent_gold_minutes,
        final_stats.custom_user_stats['PowerUp Gold'] AS breakables_broken,
        final_stats.custom_user_stats['Comeback Gold'] AS comeback_gold,
        max_gold_player AS gold_players,
        max_gold_lane_creep AS gold_lane_creeps,
        max_gold_neutral_creep AS gold_neutrals,
        max_gold_boss AS gold_bosses,
        max_gold_treasure AS gold_treasure,
        max_gold_breakable AS gold_breakables,
        max_gold_death_loss AS gold_death_loss,
        arrayFilter(i -> (((damage_matrix.stat_type[i]) = 'damage') AND ((damage_matrix.dealer_slot[i]) = player_slot) AND ((damage_matrix.target_slot[i]) > 0)), arrayEnumerate(damage_matrix.stat_type)) AS _hero_hits,
        arrayMap(i -> (damage_matrix.source[i]), _hero_hits) AS _hh_src,
        arrayMap(i -> (damage_matrix.value[i]), _hero_hits) AS _hh_val,
        arrayMap(i -> (damage_matrix.target_slot[i]), _hero_hits) AS _hh_tgt,
        arrayMap(s -> (s NOT IN ('Bullet', 'Ability', 'Melee', 'Misc', 'UnknownAbility', 'ability_unknown')), _hh_src) AS _hh_specific,
        arrayReduce('sumMap', [arrayFilter((s, k) -> k, _hh_src, _hh_specific)], [arrayMap(v -> toUInt64(v), arrayFilter((v, k) -> k, _hh_val, _hh_specific))]) AS _by_source,
        arrayMap(s -> toString(s), _by_source.1) AS dm_sources,
        arrayMap(v -> toUInt32(v), _by_source.2) AS dm_source_damage,
        toUInt32(arraySum((v, s) -> if(s = 'Bullet', v, 0), _hh_val, _hh_src)) AS dm_bullet,
        toUInt32(arraySum((v, s) -> if(s = 'Ability', v, 0), _hh_val, _hh_src)) AS dm_ability,
        toUInt32(arraySum((v, s) -> if(s = 'Melee', v, 0), _hh_val, _hh_src)) AS dm_melee,
        arrayReduce('sumMap', [arrayFilter((t, k) -> k, _hh_tgt, _hh_specific)], [arrayMap(v -> toUInt64(v), arrayFilter((v, k) -> k, _hh_val, _hh_specific))]) AS _by_target,
        arrayMap(t -> (slot_hero_ids[t + 1]), _by_target.1) AS dm_target_hero_ids,
        arrayMap(v -> toUInt32(v), _by_target.2) AS dm_target_damage,
        toUInt32(arraySum((t, d, g, v) -> if((t = 'crowd_control') AND (d = player_slot) AND (g > 0), v, 0), damage_matrix.stat_type, damage_matrix.dealer_slot, damage_matrix.target_slot, damage_matrix.value)) AS cc_ms,
        toUInt32(arraySum((t, d, g, s, v) -> if((t = 'crowd_control') AND (d = player_slot) AND (g > 0) AND (s = 'Citadel_Graph_CrowdControl_Stun'), v, 0), damage_matrix.stat_type, damage_matrix.dealer_slot, damage_matrix.target_slot, damage_matrix.source, damage_matrix.value)) AS cc_stun_ms,
        toUInt32(arraySum((t, d, v) -> if((t = 'heal_prevented') AND (d = player_slot), v, 0), damage_matrix.stat_type, damage_matrix.dealer_slot, damage_matrix.value)) AS heal_prevented,
        toUInt32(arraySum((t, d, v) -> if((t = 'mitigated_by_source') AND (d = player_slot), v, 0), damage_matrix.stat_type, damage_matrix.dealer_slot, damage_matrix.value)) AS damage_mitigated_dm
    FROM default.match_player
    WHERE (match_mode IN ('Ranked', 'Unranked')) AND (game_mode IN ('Normal', 'StreetBrawl'))
);
